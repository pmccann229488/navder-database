-- Navder Crew Social Features migration
-- Target: authoritative Mac Mini PostgreSQL database `navder`
-- Baseline: schema-only export from Mac Mini, PostgreSQL 18.6
-- Scope: Crew Chat schema, Crew Picks, Meet-ups and responses.
-- This migration does not implement application/API behaviour.
-- BACK UP FIRST. Test on a disposable copy before applying to the Mac Mini database.

BEGIN;

-- Safety gate: the existing table was created for the planned feature. We do not
-- expect existing chat history. Abort rather than reinterpret or delete rows if any exist.
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM community.crew_message LIMIT 1) THEN
        RAISE EXCEPTION
            'community.crew_message is not empty. Stop and review its rows before applying this migration.';
    END IF;
END
$$;

-- 1. Composite unique keys are required targets for same-event foreign keys.
ALTER TABLE community.crew
    ADD CONSTRAINT crew_event_crew_uq UNIQUE (event_id, crew_id);

ALTER TABLE design.poi
    ADD CONSTRAINT poi_event_poi_uq UNIQUE (event_id, poi_id);

-- 2. Extend the planned Crew Chat history table.
ALTER TABLE community.crew_message
    DROP CONSTRAINT crew_message_type_valid;

ALTER TABLE community.crew_message
    ADD COLUMN ciphertext bytea,
    ADD COLUMN actor_kind text,
    ADD COLUMN actor_pal_id uuid,
    ADD COLUMN affected_pal_id uuid,
    ADD COLUMN idempotency_key uuid;

-- There is no legacy-history migration. The table is expected to be empty.
-- New application writes must use USER or a typed membership event.
ALTER TABLE community.crew_message
    ALTER COLUMN message DROP NOT NULL,
    ALTER COLUMN message_type SET DEFAULT 'USER',
    ALTER COLUMN idempotency_key SET NOT NULL;

ALTER TABLE community.crew_message
    ADD CONSTRAINT crew_message_type_valid CHECK (
        message_type IN ('USER', 'MEMBER_JOINED', 'MEMBER_LEFT', 'MEMBER_REMOVED')
    ),
    ADD CONSTRAINT crew_message_payload_shape CHECK (
        (
            message_type = 'USER'
            AND pal_id IS NOT NULL
            AND ciphertext IS NOT NULL
            AND message IS NULL
            AND actor_kind IS NULL
            AND actor_pal_id IS NULL
            AND affected_pal_id IS NULL
        ) OR (
            message_type IN ('MEMBER_JOINED', 'MEMBER_LEFT', 'MEMBER_REMOVED')
            AND pal_id IS NULL
            AND message IS NULL
            AND ciphertext IS NULL
            AND affected_pal_id IS NOT NULL
            AND (
                (actor_kind = 'PAL' AND actor_pal_id IS NOT NULL)
                OR (actor_kind = 'SERVICE' AND actor_pal_id IS NULL)
            )
            AND (
                (message_type IN ('MEMBER_JOINED', 'MEMBER_LEFT')
                    AND actor_kind = 'PAL' AND actor_pal_id = affected_pal_id)
                OR
                (message_type = 'MEMBER_REMOVED'
                    AND (
                        (actor_kind = 'PAL' AND actor_pal_id IS DISTINCT FROM affected_pal_id)
                        OR actor_kind = 'SERVICE'
                    ))
            )
        )
    ),
    ADD CONSTRAINT crew_message_actor_kind_valid CHECK (
        actor_kind IS NULL OR actor_kind IN ('PAL', 'SERVICE')
    ),
    ADD CONSTRAINT crew_message_idempotency_uq UNIQUE (crew_id, idempotency_key),
    ADD CONSTRAINT crew_message_actor_pal_fk FOREIGN KEY (actor_pal_id)
        REFERENCES community.pal(pal_id),
    ADD CONSTRAINT crew_message_affected_pal_fk FOREIGN KEY (affected_pal_id)
        REFERENCES community.pal(pal_id);

CREATE INDEX crew_message_crew_created_idx
    ON community.crew_message (crew_id, created_at, crew_message_id);

-- 3. Crew Picks. event_id is intentionally repeated to enforce same-event integrity.
CREATE TABLE community.crew_pick (
    crew_pick_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id bigint NOT NULL,
    crew_id bigint NOT NULL,
    poi_id bigint NOT NULL,
    created_by_pal_id uuid,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT crew_pick_crew_event_fk
        FOREIGN KEY (event_id, crew_id)
        REFERENCES community.crew (event_id, crew_id),
    CONSTRAINT crew_pick_poi_event_fk
        FOREIGN KEY (event_id, poi_id)
        REFERENCES design.poi (event_id, poi_id),
    CONSTRAINT crew_pick_creator_fk
        FOREIGN KEY (created_by_pal_id)
        REFERENCES community.pal (pal_id) ON DELETE SET NULL,
    CONSTRAINT crew_pick_one_poi_per_crew_uq UNIQUE (crew_id, poi_id)
);
CREATE INDEX crew_pick_event_crew_idx ON community.crew_pick (event_id, crew_id);
CREATE INDEX crew_pick_poi_idx ON community.crew_pick (poi_id);

-- 4. Crew-owned Meet-ups. No arbitrary expiry duration is imposed.
CREATE TABLE community.crew_meetup (
    crew_meetup_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id bigint NOT NULL,
    crew_id bigint NOT NULL,
    poi_id bigint NOT NULL,
    organiser_pal_id uuid,
    mode text NOT NULL,
    scheduled_at timestamptz,
    status text NOT NULL DEFAULT 'OPEN',
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    expires_at timestamptz,
    ended_at timestamptz,
    CONSTRAINT crew_meetup_crew_event_fk
        FOREIGN KEY (event_id, crew_id)
        REFERENCES community.crew (event_id, crew_id),
    CONSTRAINT crew_meetup_poi_event_fk
        FOREIGN KEY (event_id, poi_id)
        REFERENCES design.poi (event_id, poi_id),
    CONSTRAINT crew_meetup_organiser_fk
        FOREIGN KEY (organiser_pal_id)
        REFERENCES community.pal (pal_id) ON DELETE SET NULL,
    CONSTRAINT crew_meetup_mode_valid CHECK (mode IN ('MEET_NOW', 'SCHEDULED')),
    CONSTRAINT crew_meetup_schedule_valid CHECK (
        (mode = 'MEET_NOW' AND scheduled_at IS NULL)
        OR (mode = 'SCHEDULED' AND scheduled_at IS NOT NULL)
    ),
    CONSTRAINT crew_meetup_status_valid CHECK (status IN ('OPEN', 'CANCELLED', 'COMPLETED', 'EXPIRED')),
    CONSTRAINT crew_meetup_expiry_valid CHECK (expires_at IS NULL OR expires_at > created_at),
    CONSTRAINT crew_meetup_ended_valid CHECK (ended_at IS NULL OR ended_at >= created_at)
);
CREATE INDEX crew_meetup_event_crew_status_idx
    ON community.crew_meetup (event_id, crew_id, status, created_at DESC);
CREATE INDEX crew_meetup_expiry_idx
    ON community.crew_meetup (expires_at)
    WHERE status = 'OPEN' AND expires_at IS NOT NULL;
CREATE INDEX crew_meetup_poi_idx ON community.crew_meetup (poi_id);

-- 5. One current response per Pal per Meet-up; no attendee location is stored.
CREATE TABLE community.crew_meetup_response (
    crew_meetup_response_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    crew_meetup_id bigint NOT NULL,
    pal_id uuid NOT NULL,
    response text NOT NULL,
    responded_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT crew_meetup_response_meetup_fk
        FOREIGN KEY (crew_meetup_id)
        REFERENCES community.crew_meetup (crew_meetup_id) ON DELETE CASCADE,
    CONSTRAINT crew_meetup_response_pal_fk
        FOREIGN KEY (pal_id)
        REFERENCES community.pal (pal_id),
    CONSTRAINT crew_meetup_response_value_valid CHECK (response IN ('ON_MY_WAY', 'CANT_MAKE_IT')),
    CONSTRAINT crew_meetup_response_one_per_pal_uq UNIQUE (crew_meetup_id, pal_id)
);
CREATE INDEX crew_meetup_response_pal_idx
    ON community.crew_meetup_response (pal_id, responded_at DESC);

CREATE INDEX crew_message_affected_pal_idx
    ON community.crew_message (affected_pal_id)
    WHERE affected_pal_id IS NOT NULL;

COMMENT ON TABLE community.crew_pick IS
    'Crew-owned persistent POI picks. Creator departure does not delete the pick.';
COMMENT ON TABLE community.crew_meetup IS
    'Crew-owned rendezvous records; composite foreign keys enforce same-event Crew/POI integrity.';
COMMENT ON TABLE community.crew_meetup_response IS
    'One current response per Pal per Meet-up; no attendee location is stored.';
COMMENT ON COLUMN community.crew_message.ciphertext IS
    'Opaque client-encrypted user message bytes. Server must not write plaintext content.';
COMMENT ON COLUMN community.crew_message.idempotency_key IS
    'Stable UUID for one logical message/event operation; caller must reuse it on retries.';

COMMIT;

